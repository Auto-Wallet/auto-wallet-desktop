const KEY = "autodesktop.lang";

function initialLang(): Lang {
  const saved = localStorage.getItem(KEY);
  if (saved === "en" || saved === "zh") return saved;
  return typeof navigator !== "undefined" &&
    navigator.language?.startsWith("zh")
    ? "zh"
    : "en";
}

let lang: Lang = initialLang();
const listeners = new Set<() => void>();

export function setLang(next: Lang) {
  if (next === lang) return;
  lang = next;
  localStorage.setItem(KEY, next);
  for (const l of listeners) l();
}

/**
 * BCP-47 tag for `Intl` / `toLocale*String`. Always format dates and numbers
 * against the UI language, never the machine's locale: passing `undefined`
 * hands the job to macOS, which printed Chinese dates into the English UI.
 */
export function localeTag(l: Lang): string {
  return l === "zh" ? "zh-CN" : "en-US";
}

export type TFn = (
  key: string,
  vars?: Record<string, string | number>,
) => string;

/** Every key a locale defines. A key present in one dictionary only is invisible
 *  at runtime — `translate` quietly serves the English string — so the test suite
 *  compares the two sets instead of waiting for someone to notice. */
export function translationKeys(l: Lang): string[] {
  return Object.keys(DICT[l]);
}

/** The non-hook form of `t`. Unknown keys fall back to English, then to the key
 *  itself — so a key that exists nowhere renders as raw dotted text. */
export function translate(
  l: Lang,
  key: string,
  vars?: Record<string, string | number>,
): string {
  let s = DICT[l][key] ?? DICT.en[key] ?? key;
  if (vars)
    for (const [k, v] of Object.entries(vars))
      s = s.replace(`{${k}}`, String(v));
  return s;
}

/** Subscribe to the active language and get a translate function `t`. */
export function useT(): { t: TFn; lang: Lang } {
  const current = useSyncExternalStore(
    (cb) => {
      listeners.add(cb);
      return () => listeners.delete(cb);
    },
    () => lang,
    // Server snapshot: without it useSyncExternalStore throws under
    // renderToStaticMarkup, which the component tests use.
    () => lang,
  );
  return { t: (key, vars) => translate(current, key, vars), lang: current };
}
